// Builds suite/data/exercises.js from the sqlbox blocks of the practice pages.
// Run from anywhere:  node suite/build-exercises.mjs
// The pages stay the single source of truth; re-run after editing them.
// The builder assembles SELECT queries, so only two kinds of block go in:
//   "select" — no check script (the result of the query is compared);
//   "view"   — the solution is CREATE VIEW <name> AS <select>; the builder wraps the SELECT it
//              composes and the block's check script (SELECT * FROM <name>) grades it.
// Other DML/DDL blocks (UPDATE + INSERT, CREATE TABLE…) are skipped: they are typed, not assembled.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(here, "data", "exercises.js");

const SETS = [
  { set: "suministros", name: "SUMINISTROS", page: "practica/suministros.html" },
  { set: "scd", name: "Slow Change Dimension", page: "lessons/0052-slow-change-dimension.html" },
];

const decode = (s) =>
  s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, "&");
const plain = (s) => decode(s.replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();
const script = (body, cls) => {
  const m = body.match(new RegExp(`<script type="text/plain" class="sqlbox__${cls}">([\\s\\S]*?)</script>`));
  return m ? decode(m[1]).replace(/^\s*\n/, "").replace(/\s+$/, "") : "";
};

const exercises = [];
const skipped = [];
for (const { set, page } of SETS) {
  const html = fs.readFileSync(path.join(here, "..", page), "utf8");
  let n = 0;
  for (const m of html.matchAll(/<div class="sqlbox" data-seed="(\w+)"([^>]*)>([\s\S]*?<\/script>)\s*<\/div>/g)) {
    const [, seed, attrs, body] = m;
    const solution = script(body, "solution");
    const setup = script(body, "setup");
    const check = script(body, "check");
    const task = (body.match(/<p class="sqlbox__task">([\s\S]*?)<\/p>/) || [, ""])[1];
    const hint = (body.match(/<div class="reveal__body">([\s\S]*?)<\/div>/) || [, ""])[1];
    if (!plain(task) || !solution) throw new Error(`malformed sqlbox in ${page}`);
    const view = solution.match(/^\s*CREATE\s+VIEW\s+(\w+)\s+AS\b/i);
    let kind = null;
    if (view) kind = "view";
    else if (!check) kind = "select";
    if (!kind || (kind === "select" && !/^\s*SELECT\b/i.test(solution))) {
      skipped.push(`${set}: ${plain(task).slice(0, 60)}`);
      continue;
    }
    n += 1;
    exercises.push({
      set, n, seed, kind,
      ordered: /data-ordered/.test(attrs),
      view: view ? view[1] : "",
      task: plain(task),
      hint: plain(hint),
      setup, check, solution,
    });
  }
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  "// Generated by suite/build-exercises.mjs from practica/suministros.html and lessons/0052-*.html. Do not edit by hand.\n" +
    `window.EXERCISE_SETS = ${JSON.stringify(SETS.map(({ set, name }) => ({ set, name })))};\n` +
    `window.EXERCISES = ${JSON.stringify(exercises, null, 1)};\n`
);
const per = {};
exercises.forEach((e) => (per[e.set] = (per[e.set] || 0) + 1));
console.log("exercises:", JSON.stringify(per), "-> " + path.relative(process.cwd(), outFile));
if (skipped.length) console.log("skipped (typed, not assembled):\n  " + skipped.join("\n  "));

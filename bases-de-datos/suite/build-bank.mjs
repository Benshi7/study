// Builds suite/data/bank.js from the quiz blocks embedded in ../lessons/*.html.
// Run from anywhere:  node suite/build-bank.mjs
// The lessons stay the single source of truth; re-run after editing a lesson.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const lessonsDir = path.join(here, "..", "lessons");
const outFile = path.join(here, "data", "bank.js");

// Lesson number -> block. Keep in sync with BLOCKS in suite.js and CURRICULUM.md.
const BLOCK_BY_LESSON = (n) =>
  n <= 6 ? "fund" : n <= 14 ? "der" : n <= 26 ? "norm" : n === 27 || n === 28 || n === 41 ? "fis" : n >= 49 ? "dw" : "sql";

const squash = (s) => s.replace(/\s+/g, " ").trim();
const plain = (s) =>
  squash(s.replace(/<[^>]+>/g, ""))
    .replace(/&nbsp;/g, " ").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, "&");

const bank = [];
const lessons = [];
const seen = new Set();

for (const file of fs.readdirSync(lessonsDir).filter((f) => /^\d{4}-.*\.html$/.test(f)).sort()) {
  const html = fs.readFileSync(path.join(lessonsDir, file), "utf8");
  const num = parseInt(file.slice(0, 4), 10);
  const id = file.replace(/\.html$/, "");
  const title = plain((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [, id])[1]);
  const block = BLOCK_BY_LESSON(num);

  const questions = [];
  for (const m of html.matchAll(/<div class="quiz" data-quiz>([\s\S]*?)<\/ul>\s*<\/div>/g)) {
    const body = m[1];
    const q = squash((body.match(/<p class="quiz__q">([\s\S]*?)<\/p>/) || [, ""])[1]);
    const options = [];
    let answer = -1;
    let why = "";
    for (const b of body.matchAll(/<button\b([^>]*)>([\s\S]*?)<\/button>/g)) {
      const attrs = b[1];
      if (!/quiz__opt/.test(attrs)) continue;
      const feedback = squash((attrs.match(/data-feedback="([^"]*)"/) || [, ""])[1]);
      if (/\bdata-correct\b/.test(attrs)) { answer = options.length; why = feedback; }
      options.push(plain(b[2]));
    }
    if (!q || options.length < 2 || answer < 0) {
      console.warn(`skip: malformed quiz in ${file}: ${q.slice(0, 50)}`);
      continue;
    }
    questions.push({ q, options, answer, why });
  }
  lessons.push({ id, num, title, block, file: `../lessons/${file}`, count: questions.length });

  questions.forEach((q, i) => {
    const key = plain(q.q);
    if (seen.has(key)) return;
    seen.add(key);
    bank.push({ id: `${id}#${i + 1}`, lesson: id, block, ...q });
  });
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  "// Generated by suite/build-bank.mjs from lessons/*.html. Do not edit by hand.\n" +
    `window.LESSONS = ${JSON.stringify(lessons, null, 1)};\n` +
    `window.BANK = ${JSON.stringify(bank)};\n`
);
console.log(`lessons: ${lessons.length}, questions: ${bank.length} -> ${path.relative(process.cwd(), outFile)}`);

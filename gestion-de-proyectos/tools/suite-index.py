#!/usr/bin/env python3
"""Index the suite for the hub pages: writes assets/suite-index.js (window.SUITE_INDEX).

What it collects:
  lessons   every page in clases/ and reference/: title, its <h2> sections (id + text), the diagrams it embeds
  decks     every slides/<name>/index.html: title and number of slides
  diagrams  every diagram in tools/diagramas.py: title, subtitle and the pages that embed it

Side effect (idempotent): an <h2> without an id gets one (slug of its text), so the hub can deep-link it.
Run from anywhere, after tools/diagramas.py:  python3 tools/suite-index.py
"""
import html
import importlib.util
import json
import pathlib
import re
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
H2 = re.compile(r"<h2(\s[^>]*)?>(.*?)</h2>", re.S)
TITLE = re.compile(r"<title>(.*?)</title>", re.S)
MARK = re.compile(r"<!--diagram:([a-z0-9-]+)-->")
SKIP = {"_template.html", "index.html"}


def text(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def slug(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:40] or "seccion"


def ensure_ids(page):
    src = page.read_text(encoding="utf-8")
    used = set(re.findall(r'\sid="([^"]+)"', src))
    added = 0

    def fix(m):
        nonlocal added
        attrs = m.group(1) or ""
        if "id=" in attrs:
            return m.group(0)
        base = slug(text(m.group(2)))
        new, n = base, 2
        while new in used:
            new, n = f"{base}-{n}", n + 1
        used.add(new)
        added += 1
        return f'<h2 id="{new}"{attrs}>{m.group(2)}</h2>'

    out = H2.sub(fix, src)
    if added:
        page.write_text(out, encoding="utf-8")
    return out, added


def lessons():
    found, added = {}, 0
    pages = sorted((ROOT / "clases").glob("*.html")) + sorted((ROOT / "reference").glob("*.html"))
    for page in pages:
        if page.name in SKIP:
            continue
        src, n = ensure_ids(page)
        added += n
        t = TITLE.search(src)
        found[str(page.relative_to(ROOT))] = {
            "title": text(t.group(1)) if t else page.stem,
            "sections": [[re.search(r'id="([^"]+)"', m.group(1)).group(1), text(m.group(2))] for m in H2.finditer(src)],
            "diagrams": list(dict.fromkeys(MARK.findall(src))),
        }
    return found, added


def decks():
    out = []
    for page in sorted((ROOT / "slides").glob("*/index.html")):
        src = page.read_text(encoding="utf-8")
        t = TITLE.search(src)
        out.append({
            "path": str(page.relative_to(ROOT)),
            "title": text(t.group(1)) if t else page.parent.name,
            "slides": len(re.findall(r'<section\b[^>]*class="[^"]*\bslide\b', src)) or src.count("<section"),
        })
    return out


def diagrams(lesson_index):
    spec = importlib.util.spec_from_file_location("diagramas", ROOT / "tools" / "diagramas.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    in_decks = {str(p.relative_to(ROOT)): MARK.findall(p.read_text(encoding="utf-8"))
                for p in sorted((ROOT / "slides").glob("*/index.html"))}
    out = []
    for s, (_, title, sub) in mod.DIAGRAMS.items():
        pages = [p for p, info in lesson_index.items() if s in info["diagrams"]]
        pages += [p for p, marks in in_decks.items() if s in marks]
        out.append({"slug": s, "title": title, "sub": sub, "pages": pages})
    return out


def main():
    les, added = lessons()
    data = {"lessons": les, "decks": decks(), "diagrams": diagrams(les)}
    body = json.dumps(data, ensure_ascii=False, indent=1)
    (ROOT / "assets" / "suite-index.js").write_text(
        "// Generated by tools/suite-index.py. Do not edit by hand.\nwindow.SUITE_INDEX = " + body + ";\n",
        encoding="utf-8")
    print(f"suite-index: {len(les)} páginas, {len(data['decks'])} decks, {len(data['diagrams'])} diagramas; ids nuevos en h2: {added}")


if __name__ == "__main__":
    main()

// Builds suite/data/bank.js from the quiz blocks embedded in ../lessons/*.html.
// Run from anywhere:  node suite/build-bank.mjs
// The lessons stay the single source of truth; re-run after editing a lesson.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const lessonsDir = path.join(here, "..", "lessons");
const outFile = path.join(here, "data", "bank.js");

const BLOCK_BY_LESSON = (n) => (n <= 6 ? "intro" : n <= 11 ? "python" : n <= 15 ? "sql" : "eda");

const bank = [];
const lessons = [];
const seen = new Set();

for (const file of fs.readdirSync(lessonsDir).filter((f) => /^\d{4}-.*\.html$/.test(f)).sort()) {
  const html = fs.readFileSync(path.join(lessonsDir, file), "utf8");
  const num = parseInt(file.slice(0, 4), 10);
  const id = file.replace(/\.html$/, "");
  const title = (html.match(/<h1>([\s\S]*?)<\/h1>/) || [, id])[1].replace(/<[^>]+>/g, "").trim();
  const block = BLOCK_BY_LESSON(num);
  const match = html.match(/<script type="application\/json" class="quiz-data">([\s\S]*?)<\/script>/);
  const questions = match ? JSON.parse(match[1]) : [];
  lessons.push({ id, num, title, block, file: `../lessons/${file}`, count: questions.length });

  questions.forEach((q, i) => {
    // The interleaved review (0006) repeats questions from other lessons: keep the first copy.
    const key = q.q.replace(/\s+/g, " ").trim();
    if (seen.has(key)) return;
    seen.add(key);
    bank.push({ id: `${id}#${i + 1}`, lesson: id, block, ...q });
  });
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  "// Generated by suite/build-bank.mjs from lessons/*.html. Do not edit by hand.\n" +
    `window.LESSONS = ${JSON.stringify(lessons, null, 1)};\n` +
    `window.BANK = ${JSON.stringify(bank)};\n`
);
console.log(`lessons: ${lessons.length}, questions: ${bank.length} -> ${path.relative(process.cwd(), outFile)}`);
